    private String enumSource(EnumModel e) {
        Imports imp = new Imports(config.packageName(), localNames);
        String name = naming.enumName(e);
        StringBuilder b = new StringBuilder();
        b.append("/** The PostgreSQL enum type {@code ").append(doc(types.enumSqlName(e))).append("}. */\n");
        b.append("public enum ").append(name).append(" {\n");
        Set<String> used = new HashSet<>();
        for (int i = 0; i < e.labels().size(); i++) {
            String label = e.labels().get(i);
            String constant = uniqueName(Names.javaIdentifier(naming.enumConstant(label)), used);
            b.append("    /** Label {@code ").append(doc(label)).append("}. */\n    ").append(constant).append("(\"").append(TypeMapping.escape(label))
                    .append("\")").append(i == e.labels().size() - 1 ? ";" : ",").append('\n');
        }
        b.append("\n    /** The SQL type. */\n    public static final ").append(imp.use("ch.lxrin.ql.types.DataType")).append('<').append(name)
                .append("> TYPE = ").append(imp.use("ch.lxrin.ql.types.SqlTypes")).append(".pgEnum(\"").append(TypeMapping.escape(types.enumSqlName(e)))
                .append("\", ").append(name).append(".class, ").append(name).append("::label);\n\n");
        b.append("    private final String label;\n\n    ").append(name).append("(String label) {\n        this.label = label;\n    }\n\n");
        b.append("    /**\n     * Returns the database label.\n     *\n     * @return the label\n     */\n");
        b.append("    public String label() {\n        return label;\n    }\n}\n");
        return file(imp, b);
    }

    private String tablesSource() {
        Imports imp = new Imports(config.packageName(), localNames);
        StringBuilder b = new StringBuilder("/** All tables, for {@code import static ").append(config.packageName()).append(".Tables.*}. */\n");
        b.append("public final class Tables {\n\n");
        List<TableModel> sorted = new ArrayList<>(model.tables());
        sorted.sort(Comparator.comparing(naming::tableConstant));
        for (TableModel t : sorted) {
            String cls = entityNames.get(t) + "Table";
            b.append("    /** {@code ").append(doc(qualified(t))).append("} */\n");
            b.append("    public static final ").append(cls).append(' ').append(naming.tableConstant(t)).append(" = ").append(cls).append('.')
                    .append(naming.tableConstant(t)).append(";\n\n");
        }
        b.append("    private Tables() {\n    }\n}\n");
        return file(imp, b);
    }

