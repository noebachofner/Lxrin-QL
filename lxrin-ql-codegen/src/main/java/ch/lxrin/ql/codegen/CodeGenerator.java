    private String file(Imports imp, StringBuilder body) {
        String resolved = body.toString();
        return HEADER + "package " + config.packageName() + ";\n\n" + imp.block() + resolved;
    }

    private static String resolve(Imports imp, String expression) {
        Matcher m = TYPE_MARKER.matcher(expression);
        StringBuilder sb = new StringBuilder();
        while (m.find()) m.appendReplacement(sb, Matcher.quoteReplacement(imp.use(m.group(1))));
        m.appendTail(sb);
        return sb.toString();
    }

    private static String boxed(Imports imp, String javaType) {
        return imp.use(javaType);
    }

    private String qualified(TableModel t) {
        return t.schema() + "." + t.name();
    }

    private String schemaLiteral(String schema) {
        return schema == null || schema.equals(config.defaultSchema()) ? "null" : "\"" + TypeMapping.escape(schema) + "\"";
    }

    private static void comment(StringBuilder b, String comment, String prefix) {
        if (comment == null || comment.isBlank()) return;
        b.append('\n').append(prefix.stripTrailing()).append('\n');
        for (String line : comment.split("\\R")) b.append(prefix).append(doc(line)).append('\n');
        b.setLength(b.length() - 1);
    }

    /** Escapes text for Javadoc. */
    static String doc(String text) {
        return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("*/", "*&#47;")
                .replace("@", "&#64;").replace("{", "&#123;").replace("}", "&#125;");
    }

    private void write(Path dir, String className, String source) {
        writeFile(dir.resolve(className + ".java"), source);
    }

    private void writeFile(Path file, String content) {
        writeFile(file, content, true);
    }

    private void writeFile(Path file, String content, boolean isGenerated) {
        try {
            Files.createDirectories(file.getParent());
            byte[] bytes = content.getBytes(StandardCharsets.UTF_8);
            if (!Files.exists(file) || !java.util.Arrays.equals(Files.readAllBytes(file), bytes)) Files.write(file, bytes);
            if (isGenerated) generated.add(file);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    /** Returns the files of an earlier run (recognised by the header), so stale ones can be removed. */
    private static List<Path> previouslyGenerated(Path dir) {
        List<Path> result = new ArrayList<>();
        if (!Files.isDirectory(dir)) return result;
        try (Stream<Path> files = Files.list(dir)) {
            for (Path f : (Iterable<Path>) files::iterator) {
                if (f.toString().endsWith(".java") && Files.readString(f).startsWith(HEADER)) result.add(f);
            }
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
        return result;
    }
